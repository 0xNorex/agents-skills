"""Kaggle 免费 GPU 自托管 VoxCPM2 零样本克隆配音（替代 HF Space / ZeroGPU 排队）。

用法（CLI）：
    python rewash_tts_kaggle.py --job /home/zd/src/ai-mixcut/rewash_1149_final/job.json

被 rewash_pipeline.py 调用时走 synth_batch()：把 ref 干声 + 全片台词打进一个 Kaggle
script kernel 的源码（base64 内嵌，无需数据集），跑完只取回 voice_*.wav 再按 1.0x
裁首尾静音 + 淡入淡出落盘，产物与 HF Space 版本完全同构。

实测（Kaggle 2×Tesla T4 15GB，torch 2.11.0+cu130）：
    pip install voxcpm 35s；模型加载 129s；生成 RTF ≈ 2（2B bf16，峰值 6.0GB）；
    12 句 34s 音频共 72s 生成；单次 kernel 全流程约 6 分钟（含排队/启动）。
"""

from __future__ import annotations

import base64
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

DEFAULT_KERNEL = "ccdsas/rewash-tts-voxcpm2"
DEFAULT_CACHE_KERNEL = "ccdsas/voxcpm2-cache"
DEFAULT_ACCELERATOR = "NvidiaTeslaT4"
MODEL_ID = "openbmb/VoxCPM2"

KERNEL_TEMPLATE = '''"""auto-generated by rewash_tts_kaggle.py — do not edit"""
import base64, glob, json, os, random, subprocess, time, traceback
import numpy as np
import torch

ITEMS = json.loads(base64.b64decode("__ITEMS_B64__").decode("utf-8"))
PROMPT_TEXT = base64.b64decode("__PROMPT_B64__").decode("utf-8")
REF_B64 = "__REF_B64__"
REF_NAME = "__REF_NAME__"
JOB = "__JOB__"
OUTDIR = "/kaggle/working/out"
os.makedirs(OUTDIR, exist_ok=True)

ref_path = os.path.join("/tmp", REF_NAME)
with open(ref_path, "wb") as f:
    f.write(base64.b64decode(REF_B64))

print("gpu", subprocess.run("nvidia-smi --query-gpu=name,memory.total --format=csv,noheader",
                            shell=True, capture_output=True, text=True).stdout, flush=True)
t0 = time.time()
wheel_hits = glob.glob("/kaggle/input/**/wheels/voxcpm-*.whl", recursive=True)
if wheel_hits:
    wdir = os.path.dirname(wheel_hits[0])
    p = subprocess.run(["pip", "install", "-q", "--no-index", "--find-links", wdir, "voxcpm"],
                       text=True, capture_output=True)
    if p.returncode != 0:
        print("offline pip fallback:", p.stderr[-800:], flush=True)
        p = subprocess.run("pip install -q voxcpm", shell=True, text=True, capture_output=True)
    print("pip exit", p.returncode, "%.0fs" % (time.time() - t0), "cache=wheels", flush=True)
else:
    p = subprocess.run("pip install -q voxcpm", shell=True, text=True, capture_output=True)
    print("pip exit", p.returncode, "%.0fs" % (time.time() - t0), "cache=online", flush=True)
if p.returncode != 0:
    print(p.stdout[-2000:], p.stderr[-3000:], flush=True)

from voxcpm import VoxCPM
import soundfile as sf

t0 = time.time()
model_hits = glob.glob("/kaggle/input/**/voxcpm2/model.safetensors", recursive=True)
if model_hits:
    model_src = os.path.dirname(model_hits[0])
    model = VoxCPM.from_pretrained(model_src, load_denoiser=False, local_files_only=True)
else:
    model_src = "__MODEL_ID__"
    model = VoxCPM.from_pretrained(model_src, load_denoiser=False)
sr = model.tts_model.sample_rate
print("loaded %.0fs dtype %s sr %s src %s" % (time.time() - t0, next(model.tts_model.parameters()).dtype, sr, model_src), flush=True)

report = {"job": JOB, "model": "__MODEL_ID__", "sr": sr, "items": []}
for it in ITEMS:
    t = time.time()
    torch.cuda.reset_peak_memory_stats()
    s = __SEED__ + it["idx"]
    random.seed(s)
    np.random.seed(s)
    torch.manual_seed(s)
    torch.cuda.manual_seed_all(s)
    try:
        wav = model.generate(
            text=it["text"],
            prompt_wav_path=ref_path,
            prompt_text=PROMPT_TEXT,
            reference_wav_path=ref_path,
            cfg_value=__CFG__,
            inference_timesteps=__TIMESTEPS__,
        )
        name = "voice_%02d.wav" % it["idx"]
        sf.write(os.path.join(OUTDIR, name), wav, sr)
        rec = {"idx": it["idx"], "file": name, "ok": True,
               "audio_sec": round(len(wav) / sr, 3), "gen_sec": round(time.time() - t, 2),
               "peak_mb": round(torch.cuda.max_memory_allocated() / 1e6)}
    except Exception:
        traceback.print_exc()
        rec = {"idx": it["idx"], "ok": False}
    print("ITEM", json.dumps(rec, ensure_ascii=False), flush=True)
    report["items"].append(rec)

json.dump(report, open(os.path.join(OUTDIR, "report.json"), "w"), ensure_ascii=False, indent=1)
print("FILES", sorted(os.listdir(OUTDIR)), flush=True)
'''

KERNEL_METADATA = {
    "id": DEFAULT_KERNEL,
    "title": "rewash tts voxcpm2",
    "code_file": "main.py",
    "language": "python",
    "kernel_type": "script",
    "is_private": True,
    "enable_gpu": True,
    "enable_internet": True,
    "dataset_sources": [],
    "competition_sources": [],
    "kernel_sources": [DEFAULT_CACHE_KERNEL],
}


def _kaggle_bin() -> str:
    exe = shutil.which("kaggle")
    if not exe:
        cand = Path.home() / ".local/bin/kaggle"
        if cand.is_file():
            return str(cand)
        raise SystemExit("未找到 kaggle CLI，先 pip install kaggle 并配置 ~/.kaggle/access_token")
    return exe


def _run(cmd: list[str], timeout: float = 600) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)


def synth_batch(
    segments: list[dict],
    ref_wav: str | Path,
    ref_prompt_text: str,
    out_dir: str | Path,
    *,
    job_name: str = "job",
    cfg_value: float = 2.0,
    timesteps: int = 10,
    seed: int = 1234,
    kernel_id: str = DEFAULT_KERNEL,
    accelerator: str = DEFAULT_ACCELERATOR,
    budget_sec: int = 3600,
    poll_sec: int = 30,
    sr: int = 44100,
    log=print,
) -> list[dict]:
    """一次性把全片台词丢给 Kaggle GPU 上的 VoxCPM2 克隆，落盘 1.0x 干声。

    segments: [{"shot_index": int, "text": str, ...}]
    返回: [{"shot_index", "wav_path", "duration_sec", "provider"}]
    """
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import rewash_kit as rk

    ref_path = Path(ref_wav)
    if not ref_path.is_file():
        raise SystemExit(f"参考干声不存在: {ref_path}")
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    items = [{"idx": int(s["shot_index"]), "text": s["text"]} for s in segments]
    if not items:
        return []

    items_b64 = base64.b64encode(json.dumps(items, ensure_ascii=False).encode("utf-8")).decode("ascii")
    prompt_b64 = base64.b64encode(ref_prompt_text.encode("utf-8")).decode("ascii")
    src = (KERNEL_TEMPLATE
           .replace("__ITEMS_B64__", items_b64)
           .replace("__PROMPT_B64__", prompt_b64)
           .replace("__REF_B64__", base64.b64encode(ref_path.read_bytes()).decode())
           .replace("__REF_NAME__", ref_path.name)
           .replace("__JOB__", job_name)
           .replace("__MODEL_ID__", MODEL_ID)
           .replace("__CFG__", str(float(cfg_value)))
           .replace("__TIMESTEPS__", str(int(timesteps)))
           .replace("__SEED__", str(int(seed))))

    work = Path(tempfile.mkdtemp(prefix="rewash_tts_"))
    (work / "main.py").write_text(src, encoding="utf-8")
    meta = dict(KERNEL_METADATA)
    meta["id"] = kernel_id
    cache_kernel = os.environ.get("REWASH_TTS_CACHE_KERNEL", DEFAULT_CACHE_KERNEL).strip()
    meta["kernel_sources"] = [cache_kernel] if cache_kernel else []
    (work / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")

    kaggle = _kaggle_bin()
    log(f"[tts-kaggle] 打包 {len(items)} 句 + {ref_path.name} ({ref_path.stat().st_size/1024:.0f}KB) -> {work}")
    t0 = time.monotonic()
    p = _run([kaggle, "kernels", "push", "-p", str(work), "--accelerator", accelerator,
              "-t", str(int(budget_sec))], timeout=1800)
    if p.returncode != 0:
        raise SystemExit(f"kaggle kernels push 失败: {(p.stdout + p.stderr)[-800:]}")
    log(f"[tts-kaggle] push ok ({time.monotonic()-t0:.0f}s): {(p.stdout or '').strip().splitlines()[-1][:160]}")

    deadline = time.monotonic() + budget_sec
    status = ""
    while time.monotonic() < deadline:
        s = _run([kaggle, "kernels", "status", kernel_id], timeout=180)
        status = (s.stdout or s.stderr or "").strip().splitlines()[-1] if (s.stdout or s.stderr) else ""
        if any(k in status for k in ("COMPLETE", "ERROR", "FAILED", "CANCEL")):
            break
        time.sleep(poll_sec)
    log(f"[tts-kaggle] status {status}")
    if "COMPLETE" not in status:
        lg = _run([kaggle, "kernels", "logs", kernel_id], timeout=300)
        tail = (lg.stdout or "")[-1500:]
        raise SystemExit(f"Kaggle TTS 运行失败 {status}: {tail}")

    dl = work / "out"
    dl.mkdir(exist_ok=True)
    p = _run([kaggle, "kernels", "output", kernel_id, "-p", str(dl),
              "--file-pattern", r"out/.*\.wav$", "-q"], timeout=1800)
    if p.returncode != 0:
        raise SystemExit(f"kaggle kernels output 失败: {(p.stdout + p.stderr)[-800:]}")

    records = []
    for w in sorted(dl.rglob("voice_*.wav")):
        idx = int(w.stem.split("_")[-1])
        dst = out_dir / f"voice_{idx:02d}.wav"
        dur = rk._trim_and_fade_voice(str(w), str(dst), sr=sr)
        records.append({"shot_index": idx, "wav_path": str(dst),
                        "duration_sec": round(dur, 3), "provider": "kaggle-voxcpm2"})
        log(f"[tts-kaggle] {dst.name} <- {dur:.2f}s")
    shutil.rmtree(work, ignore_errors=True)
    log(f"[tts-kaggle] done {len(records)}/{len(items)} 句，总耗时 {time.monotonic()-t0:.0f}s")
    return records


def main() -> None:
    import argparse
    ap = argparse.ArgumentParser(description="Kaggle GPU 自托管 VoxCPM2 全片克隆配音")
    ap.add_argument("--job", required=True, help="job.json 路径")
    ap.add_argument("--out", default=None, help="输出目录，默认 <job 同级>/voice_clone")
    ap.add_argument("--seed", type=int, default=1234, help="固定随机种子（同 seed 复跑时长一致）")
    ap.add_argument("--kernel-id", default=DEFAULT_KERNEL)
    ap.add_argument("--accelerator", default=DEFAULT_ACCELERATOR)
    args = ap.parse_args()
    cfg = json.loads(Path(args.job).read_text(encoding="utf-8"))
    work = Path(args.job).resolve().parent
    out_dir = Path(args.out) if args.out else work / "voice_clone"
    recs = synth_batch(cfg["segments"], cfg["ref_wav"], cfg.get("ref_prompt_text", ""),
                       out_dir, job_name=work.name, kernel_id=args.kernel_id,
                       accelerator=args.accelerator, seed=args.seed)
    print(json.dumps(recs, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
